CALL DROP_TABLE('BOB_YEKUN_DATA_2'); 
CREATE TABLE BOB_YEKUN_DATA_2 COMPRESS FOR QUERY HIGH PARALLEL 8 AS

SELECT  A.*,
        B.GECIKME_13M
FROM
BOB_YEKUN_DATA A,
(
    SELECT  A.MUQAVILE,
            MAX(CASE WHEN PART_ID BETWEEN TO_CHAR(ADD_MONTHS(BEGINDATE, 1), 'YYYYMM')*1 AND TO_CHAR(ADD_MONTHS(BEGINDATE, 13), 'YYYYMM')*1 THEN GECIKME ELSE -1 END) AS GECIKME_13M
    FROM
    BOB_YEKUN_DATA A,
    BOB_YEKUN_DATA_2_0 B
    WHERE A.MUQAVILE = B.MUQAVILE 
    GROUP BY A.MUQAVILE
) B
WHERE A.MUQAVILE = B.MUQAVILE 

